// "mih-nah-mi". Respelled throughout using the standard English trick for
// forcing a short vowel — doubling the following consonant to close the
// syllable (the same reason "inn" reads short but a lone open "i" often
// doesn't) — applied consistently, not per-name guesswork.
//
// Important honesty note: none of these have been confirmed correct by
// actually listening to the output — there's no way to do that from here.
